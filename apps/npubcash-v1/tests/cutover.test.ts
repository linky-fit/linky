import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { SQL } from "bun";
import { nip19 } from "nostr-tools";
import { buildPlan } from "../src/cutover/plan";
import { applyPlan, assertNoOtherClients, readFork } from "../src/cutover/run";
import { Database } from "../src/db";

// Needs only a Postgres server; no mint.
const adminUrl =
  Bun.env.NPUBCASH_V1_TEST_DATABASE_URL ??
  "postgres://postgres:postgres@localhost:55432/postgres";
const suffix = Date.now();
const forkName = `npubcash_fork_test_${suffix}`;
const v3Name = `npubcash_v3_test_${suffix}`;
const urlOf = (name: string) =>
  Object.assign(new URL(adminUrl), { pathname: `/${name}` }).href;

// BOLT11 spec vector: 250,000 sat.
const INVOICE =
  "lnbc2500u1pvjluezsp5zyg3zyg3zyg3zyg3zyg3zyg3zyg3zyg3zyg3zyg3zyg3zyg3zygspp5qqqsyqcyq5rqwzqfqqqsyqcyq5rqwzqfqqqsyqcyq5rqwzqfqypqdq5xysxxatsyp3k7enxv4jsxqzpu9qrsgquk0rl77nj30yxdy8j9vdx85fkpmdla2087ne0xh8nhedh8w27kyke0lp53ut353s06fv3qfegext0eh0ymjpf39tuven09sam30g4vgpfna3rh";
const alice = "a".repeat(64);
const bob = "b".repeat(64);
const operator = "c".repeat(64);
const options = { operatorPubkey: operator, forkMintUrl: "https://cashu.cz" };
const forkProof = (amount: number, secret: string) => ({
  id: "00ad268c4d1f5826",
  amount: String(amount),
  secret,
  C: `02${secret}`,
  dleq: { e: "00", s: "00", r: "00" },
});

const admin = new SQL(adminUrl);
let fork: SQL;
let v3: SQL;

beforeAll(async () => {
  await admin.unsafe(`CREATE DATABASE ${forkName}`);
  await admin.unsafe(`CREATE DATABASE ${v3Name}`);
  fork = new SQL({ url: urlOf(forkName), max: 1 });
  v3 = new SQL({ url: urlOf(v3Name), max: 1 });

  // The fork's columns the cutover reads.
  await fork.unsafe(`
    CREATE TABLE l_users (pubkey TEXT NOT NULL UNIQUE, name TEXT UNIQUE, mint_url TEXT);
    CREATE TABLE l_transactions (
      id BIGINT PRIMARY KEY, "user" TEXT NOT NULL, mint_url TEXT NOT NULL, mint_pr TEXT NOT NULL,
      cashu_quote_id TEXT, amount BIGINT, zap_request JSONB, fulfilled BOOLEAN);
    CREATE TABLE l_claims_3 (
      id BIGINT PRIMARY KEY, "user" TEXT NOT NULL, mint_url TEXT NOT NULL, proof JSONB NOT NULL,
      status TEXT NOT NULL, transaction_id BIGINT REFERENCES l_transactions(id));
    CREATE TABLE l_service_revenue_claims (
      id SERIAL PRIMARY KEY, quote_id TEXT NOT NULL, amount BIGINT NOT NULL, proof JSONB NOT NULL);
    CREATE TABLE pgmigrations (id SERIAL PRIMARY KEY, name TEXT NOT NULL);
    INSERT INTO pgmigrations (name) VALUES ('1794043600000_reoffer-unconfirmed-claims');`);
  await fork`
    INSERT INTO l_users (pubkey, name, mint_url)
    VALUES (${alice}, 'alice', 'https://cashu.cz/'), (${bob}, NULL, 'https://cashu.cz/')`;
  await fork`
    INSERT INTO l_transactions (id, "user", mint_url, mint_pr, cashu_quote_id, amount, fulfilled)
    VALUES (1, 'alice', 'https://cashu.cz/', ${INVOICE}, 'q1', 250000, NULL),
           (2, ${nip19.npubEncode(bob)}, 'https://cashu.cz/', ${INVOICE}, 'q2', 8, true),
           (3, 'alice', 'https://cashu.cz/', ${INVOICE}, 'q3', 250000, false)`;
  await fork`
    INSERT INTO l_claims_3 (id, "user", mint_url, proof, status, transaction_id)
    VALUES (1, ${nip19.npubEncode(bob)}, 'https://cashu.cz/', ${forkProof(8, "s1")}, 'inflight', 2),
           (2, ${nip19.npubEncode(bob)}, 'https://cashu.cz/', ${forkProof(4, "s2")}, 'spent', 2),
           (3, 'alice', 'https://cashu.cz/', ${forkProof(250000, "s3")}, 'spent', 3)`;
  await fork`
    INSERT INTO l_service_revenue_claims (quote_id, amount, proof)
    VALUES ('fee1', 5000, ${forkProof(4096, "f1")}), ('fee1', 5000, ${forkProof(904, "f2")})`;

  // The part of v3's baseline migration the cutover writes, plus this service's table.
  await v3.unsafe(`
    CREATE TABLE l_users (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, pubkey TEXT NOT NULL UNIQUE,
      name TEXT UNIQUE, mint_url TEXT, lock_quote BOOLEAN DEFAULT FALSE);
    CREATE TABLE mint_quotes (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, unit TEXT NOT NULL,
      mint_url TEXT NOT NULL, payment_request TEXT NOT NULL, quote_id TEXT NOT NULL,
      expires_at TIMESTAMPTZ NOT NULL, amount INTEGER NOT NULL, pubkey TEXT NOT NULL,
      state TEXT NOT NULL, serialized_zap_request TEXT, locked BOOLEAN NOT NULL DEFAULT FALSE,
      last_polled_at TIMESTAMPTZ);`);
  const service = new Database(urlOf(v3Name));
  await service.migrate();
  await service.close();
});

afterAll(async () => {
  await fork.close();
  await v3.close();
  await admin.unsafe(`DROP DATABASE IF EXISTS ${forkName} WITH (FORCE)`);
  await admin.unsafe(`DROP DATABASE IF EXISTS ${v3Name} WITH (FORCE)`);
  await admin.close();
});

describe("cutover", () => {
  test("refuses while another client uses the fork database", async () => {
    const forkProcess = new SQL({ url: urlOf(forkName), max: 1 });
    await forkProcess`SELECT 1`;
    await expect(assertNoOtherClients(fork, v3)).rejects.toThrow(
      "fork database has 1",
    );
    await forkProcess.close();
  });

  test("copies users, open quotes and unsettled proofs into v3", async () => {
    const plan = buildPlan(await readFork(fork), options);
    expect(plan.problems).toEqual([]);
    expect(
      plan.quotes.map(({ quote_id, fork_has_proofs }) => ({
        quote_id,
        fork_has_proofs,
      })),
    ).toEqual([
      { quote_id: "q1", fork_has_proofs: false },
      { quote_id: "q3", fork_has_proofs: true },
    ]);
    await applyPlan(v3, plan);

    expect(
      await v3`SELECT pubkey, name, mint_url FROM l_users ORDER BY pubkey`,
    ).toEqual([
      { pubkey: alice, name: "alice", mint_url: "https://cashu.cz/" },
      { pubkey: bob, name: null, mint_url: "https://cashu.cz/" },
    ]);
    expect(
      await v3`
        SELECT quote_id, pubkey, amount, state, last_polled_at IS NOT NULL AS polled
        FROM mint_quotes ORDER BY quote_id`,
    ).toEqual(
      ["q1", "q3"].map((quote_id) => ({
        quote_id,
        pubkey: alice,
        amount: 250000,
        state: "UNPAID",
        polled: true,
      })),
    );

    const service = new Database(urlOf(v3Name));
    expect(await service.readyClaimsOf(bob, 100)).toEqual([
      {
        mint_url: "https://cashu.cz/",
        quote_id: "q2",
        pubkey: bob,
        amount: 8,
        output_amounts: null,
        proofs: [
          { id: "00ad268c4d1f5826", amount: 8, secret: "s1", C: "02s1" },
        ],
        status: "ready",
      },
    ]);
    const [fee] = await service.readyClaimsOf(operator, 100);
    expect(fee?.mint_url).toBe("https://cashu.cz");
    expect(fee?.amount).toBe(5000);
    expect(fee?.proofs?.map(({ amount }) => amount)).toEqual([4096, 904]);
    await service.close();
  });

  test("refuses a second run", async () => {
    const plan = buildPlan(await readFork(fork), options);
    await expect(applyPlan(v3, plan)).rejects.toThrow(
      "v3 database already holds users, quotes or claims",
    );
  });
});
