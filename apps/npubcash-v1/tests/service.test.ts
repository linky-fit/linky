// Needs a Postgres server and the dev-stack nutshell FakeWallet mint, which
// settles every invoice it issues: `docker compose -f docker-compose.dev.yml up -d --wait cashu-mint`.
const adminUrl =
  Bun.env.NPUBCASH_V1_TEST_DATABASE_URL ??
  "postgres://postgres:postgres@localhost:55432/postgres";
const mintUrl = Bun.env.NPUBCASH_V1_TEST_MINT_URL ?? "http://localhost:3338";
setDefaultTimeout(30_000);

const databaseName = `npubcash_v1_test_${Date.now()}`;

const operatorKey = generateSecretKey();
const config: ServiceConfig = {
  port: 0,
  databaseUrl: Object.assign(new URL(adminUrl), {
    pathname: `/${databaseName}`,
  }).href,
  seed: crypto.getRandomValues(new Uint8Array(32)),
  jwtSecret: "test-secret",
  defaultMintUrl: mintUrl,
  operatorPubkey: getPublicKey(operatorKey),
  workerIntervalMs: 1000,
  buildCommitSha: "test",
};

const admin = new SQL(adminUrl);
let db: Database;
let minter: Minter;
let handle: (request: Request) => Promise<Response>;
const mint = new Mint(mintUrl);

const tick = () => runWorkerTick(db, minter);

async function until<T>(read: () => Promise<T>, done: (value: T) => boolean) {
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const value = await read();
    if (done(value)) return value;
    await Bun.sleep(250);
  }
  throw new Error("timed out");
}

const paidQuote = async (amount: number) => {
  const quote = await mint.createMintQuoteBolt11({ amount, unit: "sat" });
  await until(
    () => mint.checkMintQuoteBolt11(quote.quote),
    ({ state }) => state === MintQuoteState.PAID,
  );
  return quote;
};

/** A paid quote as v3's poller leaves it. */
const insertV3Quote = async (pubkey: string, amount: number) => {
  const quote = await paidQuote(amount);
  await db.sql`
    INSERT INTO mint_quotes (unit, mint_url, payment_request, quote_id, expires_at, amount, pubkey, state)
    VALUES ('sat', ${mintUrl}, ${quote.request}, ${quote.quote}, NOW() + interval '1 hour', ${amount}, ${pubkey}, 'PAID')`;
  return quote.quote;
};

const decodeBody = Schema.decodeUnknownSync(
  Schema.NullOr(
    Schema.Struct({
      error: Schema.optional(Schema.Boolean),
      message: Schema.optional(Schema.String),
      username: Schema.optional(Schema.NullOr(Schema.String)),
      mintUrl: Schema.optional(Schema.NullOr(Schema.String)),
      data: Schema.optional(
        Schema.Struct({
          token: Schema.optional(Schema.String),
          tokens: Schema.optional(Schema.Array(Schema.String)),
          paymentToken: Schema.optional(Schema.String),
        }),
      ),
    }),
  ),
);

const call = async (
  secretKey: Uint8Array,
  method: string,
  path: string,
  body?: Record<string, string>,
) => {
  const authorization = await nip98.getToken(
    `https://npub.linky.fit${path}`,
    method,
    (event) => finalizeEvent(event, secretKey),
    true,
  );
  const response = await handle(
    new Request(`http://localhost${path}`, {
      method,
      headers: {
        authorization,
        host: "npub.linky.fit",
        "x-forwarded-proto": "https",
        "content-type": "application/json",
      },
      ...(body ? { body: JSON.stringify(body) } : {}),
    }),
  );
  const text = await response.text();
  return {
    status: response.status,
    body: decodeBody(text ? JSON.parse(text) : null),
  };
};

const claimOf = async (quoteId: string) =>
  db.claim({ mint_url: mintUrl, quote_id: quoteId });

const v3QuoteState = async (quoteId: string) => {
  const [row]: { state: string }[] =
    await db.sql`SELECT state FROM mint_quotes WHERE quote_id = ${quoteId}`;
  return row?.state;
};

beforeAll(async () => {
  await admin.unsafe(`CREATE DATABASE ${databaseName}`);
  db = new Database(config.databaseUrl);
  // The part of v3's baseline migration this service touches.
  await db.sql`
    CREATE TABLE l_users (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      pubkey TEXT NOT NULL UNIQUE,
      name TEXT UNIQUE,
      mint_url TEXT,
      lock_quote BOOLEAN DEFAULT FALSE
    )`;
  await db.sql`
    CREATE TABLE mint_quotes (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      unit TEXT NOT NULL,
      mint_url TEXT NOT NULL,
      payment_request TEXT NOT NULL,
      quote_id TEXT NOT NULL,
      expires_at TIMESTAMPTZ NOT NULL,
      amount INTEGER NOT NULL,
      pubkey TEXT NOT NULL,
      state TEXT NOT NULL,
      paid_at TIMESTAMPTZ,
      serialized_zap_request TEXT,
      locked BOOLEAN NOT NULL DEFAULT FALSE
    )`;
  await db.migrate();
  minter = new Minter(db, config.seed);
  handle = createHttpHandler({ config, db, minter });
});

afterAll(async () => {
  await db.close();
  await admin.unsafe(`DROP DATABASE IF EXISTS ${databaseName} WITH (FORCE)`);
  await admin.close();
});

describe("worker and claim", () => {
  test("mints a paid v3 quote, offers its proofs until they are spent", async () => {
    const userKey = generateSecretKey();
    const quoteId = await insertV3Quote(getPublicKey(userKey), 21);

    await tick();
    expect((await claimOf(quoteId))?.status).toBe("ready");
    expect(await v3QuoteState(quoteId)).toBe("ISSUED");

    const first = await call(userKey, "GET", "/api/v1/claim");
    const again = await call(userKey, "GET", "/api/v1/claim");
    const token = first.body?.data?.token ?? "";
    expect(first.body).toEqual({
      error: false,
      data: { token, tokens: [token] },
    });
    expect(again.body?.data?.token).toBe(token);

    const wallet = new Wallet(mintUrl);
    await wallet.loadMint();
    const received = await wallet.receive(token);
    expect(received.length).toBeGreaterThan(0);

    expect(await call(userKey, "GET", "/api/v1/claim")).toEqual({
      status: 200,
      body: { error: true, message: "No proofs to claim" },
    });
    expect((await claimOf(quoteId))?.status).toBe("spent");
  });

  test("skips quotes locked to the user's key", async () => {
    const quoteId = await insertV3Quote(getPublicKey(generateSecretKey()), 8);
    await db.sql`UPDATE mint_quotes SET locked = true WHERE quote_id = ${quoteId}`;
    await tick();
    expect(await claimOf(quoteId)).toBeUndefined();
  });

  test("restores a mint whose response was lost", async () => {
    const quote = await paidQuote(13);
    const row = {
      mint_url: mintUrl,
      quote_id: quote.quote,
      pubkey: getPublicKey(generateSecretKey()),
      amount: 13,
      output_amounts: [1, 4, 8],
      status: "minting" as const,
    };
    await db.insertClaim(row);
    const { keysets } = await mint.getKeySets();
    const keysetId = keysets.find((keyset) => keyset.active)?.id ?? "";
    await mint.mintBolt11({
      quote: quote.quote,
      outputs: deriveOutputs(
        config.seed,
        mintUrl,
        quote.quote,
        [1, 4, 8],
        keysetId,
      ).map((output) => output.blindedMessage),
    });

    await tick();
    const restored = await claimOf(quote.quote);
    expect(restored?.status).toBe("ready");
    expect(restored?.proofs?.map((proof) => proof.amount)).toEqual([1, 4, 8]);
  });

  test("marks a quote someone else minted as issued_elsewhere", async () => {
    const quoteId = await insertV3Quote(getPublicKey(generateSecretKey()), 5);
    const wallet = new Wallet(mintUrl);
    await wallet.loadMint();
    await wallet.mintProofsBolt11(5, quoteId);

    await tick();
    expect((await claimOf(quoteId))?.status).toBe("issued_elsewhere");
  });

  test("keeps the proofs of a mint that finished after a concurrent caller saw ISSUED", async () => {
    const key = { mint_url: mintUrl, quote_id: "raced-quote" };
    await db.insertClaim({
      ...key,
      pubkey: getPublicKey(generateSecretKey()),
      amount: 1,
      output_amounts: [1],
      status: "minting",
    });
    await db.moveClaim(key, "minting", "issued_elsewhere");
    await db.storeProofs(key, [{ id: "00", amount: 1, secret: "s", C: "c" }]);
    expect((await claimOf(key.quote_id))?.status).toBe("ready");
  });
});

describe("info", () => {
  test("falls back to the default mint and stores a new one", async () => {
    const userKey = generateSecretKey();
    expect((await call(userKey, "GET", "/api/v1/info")).body).toMatchObject({
      username: null,
      mintUrl,
    });
    const put = await call(userKey, "PUT", "/api/v1/info/mint", {
      mintUrl: "https://mint.example",
    });
    expect(put.status).toBe(204);
    expect((await call(userKey, "GET", "/api/v1/info")).body).toMatchObject({
      mintUrl: "https://mint.example/",
    });
  });

  test("rejects a request signed for another host", async () => {
    const userKey = generateSecretKey();
    const authorization = await nip98.getToken(
      "https://npub.cash/api/v1/info",
      "GET",
      (event) => finalizeEvent(event, userKey),
      true,
    );
    const response = await handle(
      new Request("http://localhost/api/v1/info", {
        headers: {
          authorization,
          host: "npub.linky.fit",
          "x-forwarded-proto": "https",
        },
      }),
    );
    expect(response.status).toBe(401);
  });
});

describe("username purchase", () => {
  const offer = async (userKey: Uint8Array, username: string) => {
    const response = await call(userKey, "PUT", "/api/v1/info/username", {
      username,
    });
    expect(response.status).toBe(402);
    return response.body?.data?.paymentToken ?? "";
  };

  test("sets the name once the fee is minted, and keeps it", async () => {
    const userKey = generateSecretKey();
    const paymentToken = await offer(userKey, "Alice");

    const result = await until(
      () =>
        call(userKey, "PUT", "/api/v1/info/username", {
          username: "alice",
          paymentToken,
        }),
      ({ status }) => status !== 402,
    );
    expect(result).toEqual({ status: 200, body: { error: false } });
    expect((await call(userKey, "GET", "/api/v1/info")).body).toMatchObject({
      username: "alice",
      mintUrl,
    });

    const [fee] = await db
      .claimsWithStatus("ready")
      .then((rows) =>
        rows.filter((row) => row.pubkey === config.operatorPubkey),
      );
    expect(fee?.amount).toBe(5000);

    const retry = await call(userKey, "PUT", "/api/v1/info/username", {
      username: "alice",
      paymentToken,
    });
    expect(retry.body?.message).toBe("Username already set");
  });

  test("refuses a token signed for another name", async () => {
    const userKey = generateSecretKey();
    const paymentToken = await offer(userKey, "bobby");
    const response = await call(userKey, "PUT", "/api/v1/info/username", {
      username: "satoshi",
      paymentToken,
    });
    expect(response).toEqual({
      status: 403,
      body: { error: true, message: "Forbidden!" },
    });
  });

  test("gives a contested name to one buyer", async () => {
    const buyers = [generateSecretKey(), generateSecretKey()];
    const tokens = await Promise.all(buyers.map((key) => offer(key, "carol")));
    const results = await Promise.all(
      buyers.map((key, index) =>
        until(
          () =>
            call(key, "PUT", "/api/v1/info/username", {
              username: "carol",
              paymentToken: tokens[index] ?? "",
            }),
          ({ status }) => status !== 402,
        ),
      ),
    );
    expect(results.filter(({ status }) => status === 200)).toHaveLength(1);
    const [owner]: { count: number }[] =
      await db.sql`SELECT COUNT(*)::int AS count FROM l_users WHERE name = 'carol'`;
    expect(owner?.count).toBe(1);
  });
});
